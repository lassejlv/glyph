function matches(name, tags, terms) {
  const hay = [name, ...(tags[name] || [])].join(" ").toLowerCase();
  return terms.every((t) => hay.includes(t));
}

function filter(cardMap, tags, terms) {
  let shown = 0;
  for (const [name, card] of cardMap) {
    const ok = matches(name, tags, terms);
    card.hidden = !ok;
    if (ok) shown++;
  }
  return shown;
}

